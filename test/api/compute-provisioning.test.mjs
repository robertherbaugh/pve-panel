import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { startStack, waitFor } from '../support/stack.mjs';
let stack, admin, user, customerId, sql;
const input = (hostname, extra = {}) => ({ hostname, templateId: 9000, sizeId: 'small', storageClassId: 'fast', diskGb: 20, username: 'debian', password: 'compute-password-123', ...extra });
async function create(body, key = randomUUID()) {
 const res = await fetch(user.base + '/api/vms', { method: 'POST', headers: { cookie: [...user.cookies].map(([k,v]) => `${k}=${v}`).join('; '), 'content-type':'application/json', 'idempotency-key': key }, body: JSON.stringify(body) });
 return { status: res.status, json: await res.json() };
}
const catalogBody = c => ({ revision:c.revision, sizes:c.sizes, classes:c.classes.map(({id,enabled,bindings})=>({id,enabled,bindings})),reserves:c.reserves });
before(async () => {
 stack = await startStack({env:{CUSTOMER_NETWORKS:'false',VPN_ENABLED:'false', SETUP_CHECK_HOURS:'0'}}); admin = await stack.adminSession();
 await stack.offerTemplates(); user = await stack.customerWith('compute-vm@example.com',{limits:{maxServers:10,maxCores:32,maxMemoryMb:65536,maxDiskGb:1000}});
 customerId=(await admin.get('/api/admin/customers')).json.customers.find(c=>c.name==='compute-vm@example.com').id;
 sql=new DatabaseSync(path.join(stack.dir,'panel.db'));
 stack.mock.perms['/vms']=['VM.Audit'];stack.mock.perms['/pool/customers'].push('Pool.Audit');
 stack.mock.cluster.nodes=[{node:'pve1',status:'online',maxcpu:32,maxmem:128*2**30,mem:32*2**30},{node:'pve2',status:'online',maxcpu:32,maxmem:128*2**30,mem:2**30}];
 const stores=[{storage:'VMStorage',content:'images,rootdir',active:1,enabled:1,shared:1,total:1000*2**30,avail:900*2**30},{storage:'nvme',content:'images,rootdir',active:1,enabled:1,shared:0,total:1000*2**30,avail:900*2**30}];
 stack.mock.cluster.storageInventories={pve1:structuredClone(stores),pve2:structuredClone(stores)};
 let c=catalogBody((await admin.get('/api/admin/compute-catalog')).json); c.sizes[0].enabled=true;
 c.classes.find(c=>c.id==='fast').enabled=true;c.classes.find(c=>c.id==='fast').bindings=[{node:'pve1',storage:'nvme',purpose:'vm'},{node:'pve2',storage:'nvme',purpose:'vm'}];
 assert.equal((await admin.put('/api/admin/compute-catalog',c)).status,200);
 const p=(await admin.get(`/api/admin/customers/${customerId}/compute-profile`)).json;
 assert.equal((await admin.put(`/api/admin/customers/${customerId}/compute-profile`,{revision:p.revision,catalogRevision:c.revision+1,tier:p.tier,sizeIds:p.sizeIds,storageClassIds:p.storageClassIds,haAllowed:p.haAllowed,backupServiceEnabled:p.backupServiceEnabled,storageLimitsGb:p.storageLimitsGb,backupLimitGb:p.backupLimitGb,catalogEnabled:true,network:{bridge:'vmbr0',vlan:47,verified:true}})).status,200);
});
after(async()=>{sql?.close();await stack?.stop();});
let vmid;
test('catalog provisioning derives size, clones to another node and records its allocation',async()=>{
 const key=randomUUID(), request=input('catalog-web');
 const r=await create(request,key);assert.equal(r.status,202,JSON.stringify(r.json));vmid=r.json.vmid;
 const op=sql.prepare('SELECT * FROM compute_operations WHERE vmid=? ORDER BY rowid DESC LIMIT 1').get(vmid);
 assert.ok(op);assert.notEqual(op.credentials,null);assert.ok(!JSON.stringify(op).includes(request.password));
 assert.equal(stack.mock.vms.get(vmid).node,'pve2');
 const settled=await stack.serverSettled(user,vmid);assert.equal(settled.state,'ready',settled.error);
 assert.equal(stack.mock.vms.get(vmid).cfg.cores,'1');assert.match(stack.mock.vms.get(vmid).cfg.scsi0,/^nvme:/);
 assert.match(stack.mock.vms.get(vmid).cfg.net0,/bridge=vmbr0,tag=47,firewall=1/);
 const final=sql.prepare('SELECT * FROM compute_operations WHERE vmid=? ORDER BY rowid DESC LIMIT 1').get(vmid);assert.equal(final.state,'complete');assert.equal(final.credentials,null);
 const history=(await user.get('/api/compute-allocations')).json.events;assert.equal(history.length,1);assert.equal(history[0].offering.storageClassId,'fast');
 assert.equal((await create(request,key)).json.vmid,vmid);assert.equal(sql.prepare('SELECT count(*) n FROM compute_operations').get().n,1);
 assert.equal((await create({...request,hostname:'changed'},key)).status,409);
});
test('catalog customers cannot bypass size selection, class restrictions or provisioning permissions',async()=>{
 assert.equal((await create(input('raw',{sizeId:undefined,storageClassId:undefined,cores:8,memoryMb:8192}))).status,400);
 assert.equal((await create(input('bad-cpu',{cores:128}))).status,400);
 assert.equal((await create(input('disabled-size',{sizeId:'medium'}))).status,400);
 assert.equal((await create(input('disabled-class',{storageClassId:'standard'}))).status,400);
 assert.equal((await create(input('ha-bypass',{haEnabled:true}))).status,400);
 assert.equal((await user.post('/api/vms',input('no-key'))).status,400);
 const peer=await stack.customerWith('no-create@example.com');assert.equal((await peer.post('/api/vms',input('no-permission'))).status,403);
 assert.equal((await peer.get('/api/compute-allocations')).json.events.length,0);
});
